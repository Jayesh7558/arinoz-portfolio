    <script>
        document.addEventListener("DOMContentLoaded", function () {

            const accordionItems = document.querySelectorAll(".accordion-box .accordion");

            if (!accordionItems.length) return;

            // Open the first FAQ when the page loads
            accordionItems[0].classList.add("active");

            const firstContent = accordionItems[0].querySelector(".acc-content");
            if (firstContent) {
                firstContent.style.display = "block";
            }

            accordionItems.forEach(function (item) {

                const button = item.querySelector(".acc-btn");
                const content = item.querySelector(".acc-content");

                if (!button || !content) return;

                button.addEventListener("click", function () {

                    const isAlreadyActive = item.classList.contains("active");

                    // Close all FAQ items first
                    accordionItems.forEach(function (otherItem) {
                        otherItem.classList.remove("active");
                        const otherContent = otherItem.querySelector(".acc-content");
                        if (otherContent) {
                            otherContent.style.display = "none";
                        }
                    });

                    // Open clicked FAQ
                    if (!isAlreadyActive) {
                        item.classList.add("active");
                        content.style.display = "block";
                    }
                });
            });
        });
    </script>

